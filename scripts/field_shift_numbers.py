"""Tables for the submission (video, slides, README) generated from a Field Shift v2 package. No number is typed by hand.

Usage: python scripts/field_shift_numbers.py <package directory> <output markdown>
"""
import hashlib
from decimal import ROUND_HALF_UP, Decimal
import json
import sys
from pathlib import Path

LABEL = {'reference_fallow': 'A: soy -> second-crop maize -> bare fallow (reference of the demonstration)',
         'brachiaria': 'B: soy -> maize with Brachiaria -> cover until desiccation',
         'soy_long_fallow': 'C: soy -> bare fallow until the next soy (no maize; fewer crops, not a diversified rotation)'}
ROWS = (('covered_days', 'Days with a crop or cover present', 'days/year'), ('bare_days', 'Days without crop or cover', 'days/year'),
        ('year_rain_mm', 'Rain in the agricultural year', 'mm/year'), ('year_water_use_mm', 'Water used (actual evapotranspiration)', 'mm/year'),
        ('year_drainage_mm', 'Water drained below the root zone', 'mm/year'), ('storage_at_next_sowing_mm', 'Soil water reserve before the next soy', 'mm'),
        ('soy_deficit_mm', 'Soy water deficit (ETc - ETa)', 'mm/cycle'), ('soy_stress_days', 'Soy stress days', 'days/cycle'),
        ('next_soy_establishment_deficit_mm', 'Deficit in the first 15 days of the next soy', 'mm'),
        ('maize_deficit_mm', 'Maize water deficit (ETc - ETa)', 'mm/cycle'), ('maize_stress_days', 'Maize stress days', 'days/cycle'))
IDS = ('reference_fallow', 'brachiaria', 'soy_long_fallow')
LETTER = {'reference_fallow': 'A', 'brachiaria': 'B', 'soy_long_fallow': 'C'}


def one(value):
    """One decimal, half up on the published decimal value — the same reading the app shows."""
    return Decimal(str(value)).quantize(Decimal('0.1'), rounding=ROUND_HALF_UP)


def cell(value):
    return 'not grown' if value is None else f'{one(value)}'


def delta(value):
    value = one(value)
    return '0.0' if value == 0 else f'{value:+}'


def signed(stat):
    if stat['mean'] is None:
        return 'not applicable'
    low, high = delta(stat['min']), delta(stat['max'])
    spread = '' if low == high else f', range across seasons {low} to {high}'
    return f'{delta(stat["mean"])} (n = {stat["n"]}{spread})'


def main(package, output):
    package = Path(package)
    manifest = json.loads((package / 'manifest.json').read_text(encoding='utf-8'))
    s = json.loads((package / 'summary.json').read_text(encoding='utf-8'))
    for name, meta in manifest['files'].items():
        if hashlib.sha256((package / name).read_bytes()).hexdigest() != meta['sha256']:
            raise SystemExit(f'{name} does not match the manifest; refusing to write numbers')
    years = s['weather']['agricultural_years']
    out = ['# Field Shift — numbers for the submission', '',
           f'Generated by `scripts/field_shift_numbers.py` from package `{s["package_id"]}`. Do not edit by hand; regenerate.', '',
           '## What these numbers are', '',
           f'- Place: {s["municipality"]} (IBGE {s["municipality_code"]}); scale: {s["scale"]}.',
           f'- Period: {len(years)} agricultural seasons, {years[0]} to {years[-1]} (retrospective). Aggregation: mean of the seasons.',
           f'- Weather: {s["weather"]["source"]}; {s["weather"]["days"]} days, {s["weather"]["first_day"]} to {s["weather"]["last_day"]}; forcing sha256 `{s["weather"]["sha256"]}`.',
           f'- Soil hypothesis: class {s["soil"]["cad_class"]}, {s["soil"]["capacity_mm"]:.0f} mm of available water, initial reserve {s["soil"]["initial_storage_fraction"]} of capacity, carried continuously between seasons.',
           f'- Hypotheses: cover Kc {s["hypotheses"]["central"]["cover_kc"]}, straw factor {s["hypotheses"]["central"]["straw_factor"]}, bare fallow Kc {s["hypotheses"]["fallow_kc"]}, soy sown on 5 October (fixed calendar).',
           '- Nature: simulation under stated hypotheses. Retrospective, not operational and not a forecast. ' + s['evidence'],
           f'- Not simulated: {", ".join(s["not_simulated"])}. Yield effect: none claimed.',
           f'- Package files: summary `{manifest["files"]["summary.json"]["sha256"]}`, series `{manifest["files"]["series.json"]["sha256"]}`; generated at {manifest["generated_at"]}.',
           '- Code identity: sha256 of ' + ', '.join(f'`{name}` `{digest[:12]}`' for name, digest in manifest['identity']['code'].items()) + '. These digests, not a commit name, identify the code: the manifest field `base_git_revision` is only the HEAD of the working tree at generation, which had uncommitted changes.',
           '', '## Strategies', ''] + [f'- {LABEL[i]}' for i in IDS] + ['', '## Means of the seasons', '',
           '| Indicator | Unit | A | B | C | B − A | C − A |', '|---|---|---:|---:|---:|---|---|']
    for key, label, unit in ROWS:
        values = [cell(s['scenarios'][i]['mean'][key]) for i in IDS]
        out.append(f'| {label} | {unit} | {values[0]} | {values[1]} | {values[2]} | {signed(s["comparisons"]["brachiaria_minus_reference_fallow"][key])} | {signed(s["comparisons"]["soy_long_fallow_minus_reference_fallow"][key])} |')
    out += ['', 'Differences are paired season by season; the range is the smallest and largest difference among the seasons, not a prediction interval.',
            'Drainage is water leaving the modelled root zone; it does not measure erosion, leaching or infiltration.',
            '"Crop or cover present" is a yes/no state of each day, not a measured ground-cover percentage.', '',
            '## Rain sensitivity (same daily sequence, rain multiplied; not a climate forecast)', '',
            '| Rain | Strategy | Rain (mm/year) | Water used (mm/year) | Drained (mm/year) | Reserve before next soy (mm) | Soy deficit (mm) | Maize deficit (mm) |', '|---|---|---:|---:|---:|---:|---:|---:|']
    for point in s['sensitivity']['rain']['points']:
        for i in IDS:
            m = point['scenarios'][i]['mean']
            out.append(f'| {point["rain_change_percent"]:+d}% | {LETTER[i]} | {m["year_rain_mm"]:.0f} | {cell(m["year_water_use_mm"])} | {cell(m["year_drainage_mm"])} | {cell(m["storage_at_next_sowing_mm"])} | {cell(m["soy_deficit_mm"])} | {cell(m["maize_deficit_mm"])} |')
    out += ['', f'Temperature: {s["sensitivity"]["temperature"]["status"]} — {s["sensitivity"]["temperature"]["reason"]}.', '']
    Path(output).write_text('\n'.join(out), encoding='utf-8', newline='\n')
    print(output)


if __name__ == '__main__':
    main(*sys.argv[1:3])
